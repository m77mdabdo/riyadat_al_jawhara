<?php

namespace App\Console\Commands;

use App\Support\SiteImages;
use Illuminate\Console\Command;
use Illuminate\Support\Facades\File;

/**
 * Chooses a candidate for a slot (the best-scored one, or a given ID), copies
 * it to public/images/site/{slot}.webp, records it in
 * resources/data/site-images.json and regenerates docs/IMAGE_CREDITS.md.
 */
class SiteImagesPick extends Command
{
    protected $signature = 'site-images:pick
                            {slot? : Slot key (default: auto-pick every slot that has candidates)}
                            {candidate? : Candidate ID, e.g. pexels-123456 (default: best score)}';

    protected $description = 'Pick a stock candidate for a static image slot and update the credits';

    public function handle(): int
    {
        $slots = $this->argument('slot') ? [$this->argument('slot')] : array_keys(config('site-images.slots'));
        $state = SiteImages::choices();

        foreach ($slots as $slot) {
            $listFile = storage_path("app/stock-candidates/{$slot}/candidates.json");
            if (! is_file($listFile)) {
                $this->warn("{$slot}: no candidates (run site-images:candidates {$slot})");

                continue;
            }

            $candidates = json_decode(file_get_contents($listFile), true);
            $wanted = $this->argument('candidate');
            $choice = $wanted
                ? collect($candidates)->firstWhere('id', $wanted)
                : ($candidates[0] ?? null);

            if (! $choice) {
                $this->error("{$slot}: candidate ".($wanted ?? '(best)').' not found');

                return self::FAILURE;
            }

            File::ensureDirectoryExists(public_path(SiteImages::DIRECTORY));
            File::copy(storage_path('app/stock-candidates/'.$choice['file']), SiteImages::path($slot));
            $this->callSilently('site-images:variants', ['slot' => $slot]);

            $state[$slot] = collect($choice)->only([
                'id', 'source', 'photographer', 'photographer_url', 'page_url', 'license_url',
                'score', 'brightness', 'warmth', 'saved_width', 'saved_height', 'kb',
            ])->all() + ['picked' => $wanted ? 'manual' : 'auto'];

            $this->info("{$slot}: {$choice['id']} ({$state[$slot]['picked']})");
        }

        ksort($state);
        File::ensureDirectoryExists(dirname(config('site-images.state_path')));
        File::put(config('site-images.state_path'), json_encode($state, JSON_PRETTY_PRINT | JSON_UNESCAPED_SLASHES | JSON_UNESCAPED_UNICODE)."\n");
        $this->writeCredits($state);

        return self::SUCCESS;
    }

    private function writeCredits(array $state): void
    {
        $slots = config('site-images.slots');
        $rows = collect($state)->map(fn ($c, $slot) => sprintf(
            '| `public/%s/%s.webp` | %s | %s | %s | %s | %s |',
            SiteImages::DIRECTORY,
            $slot,
            $slots[$slot]['used'] ?? $slot,
            $c['source'],
            $c['photographer_url'] ? "[{$c['photographer']}]({$c['photographer_url']})" : ($c['photographer'] ?? '—'),
            $c['page_url'] ? "[{$c['id']}]({$c['page_url']})" : $c['id'],
            "[licence]({$c['license_url']})",
        ));

        $creditsPath = config('site-images.credits_path');
        $existing = is_file($creditsPath) ? file_get_contents($creditsPath) : '';
        $media = str_contains($existing, '<!-- media-library -->')
            ? substr($existing, strpos($existing, '<!-- media-library -->'))
            : "<!-- media-library -->\n## Media Library attachments\n\n_None._\n";

        File::ensureDirectoryExists(dirname($creditsPath));
        File::put($creditsPath, implode("\n", [
            '# Image credits',
            '',
            'All photos are stock images downloaded locally (no hotlinking), resized to ≤ 1920 px and converted to WebP.',
            'Pexels and Pixabay licences allow commercial use without attribution; credits are recorded anyway.',
            'Generated by `php artisan site-images:pick`. Do not edit the static table by hand.',
            '',
            '## Static site images',
            '',
            '| file | used where | source | photographer | original URL | license link |',
            '|---|---|---|---|---|---|',
            ...$rows->values()->all(),
            '',
            $media,
        ]));
    }
}
